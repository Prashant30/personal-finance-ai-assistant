package dev.prashant.finance.assistant;

import io.swagger.v3.oas.annotations.Operation;
import jakarta.validation.Valid;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/assistant/questions")
public class AssistantController {

    private final AssistantService assistantService;

    public AssistantController(AssistantService assistantService) {
        this.assistantService = assistantService;
    }

    @PostMapping
    @Operation(summary = "Ask an evidence-backed question about fictional spending")
    QuestionResponse ask(@Valid @RequestBody QuestionRequest request) {
        return assistantService.answer(request.question());
    }
}

